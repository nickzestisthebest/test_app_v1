import os
from playwright.sync_api import sync_playwright
R=[]
def ck(n,c,d=''):R.append(c);print('PASS' if c else 'FAIL',n,d)
with sync_playwright() as p:
    b=p.chromium.launch(executable_path='/opt/pw-browsers/chromium')
    ctx=b.new_context(viewport={'width':390,'height':844},has_touch=True,is_mobile=True,device_scale_factor=2)
    pg=ctx.new_page();errs=[];pg.on('pageerror',lambda e:errs.append(str(e)))
    pg.add_init_script("window.claude={use:async()=>{throw new Error('x')}}")
    pg.goto('file://'+os.getcwd()+'/v2_test.html');pg.wait_for_timeout(3400)
    pg.tap('[data-wact=demo2]');pg.wait_for_timeout(5500)
    ck('hero says Budget score','Budget score' in pg.inner_text('.ovhero'))
    ck('no Health label in hero','Health' not in pg.inner_text('.ovhero'))
    gap=pg.evaluate("(()=>{const h=document.querySelector('.ovhero'),a=h.firstElementChild.getBoundingClientRect(),s=h.querySelector('.ovscore').getBoundingClientRect(),n=h.querySelector('.ovscore').previousElementSibling;return Math.round(s.left-[...h.firstElementChild.querySelectorAll('*')].reduce((m,e)=>Math.max(m,e.getBoundingClientRect().right),0))})()")
    ck('gap between number and score is small',gap<90,gap)
    ck('Budget score section title',pg.locator('#m-health .mt b').inner_text()=='Budget score')
    cdp=ctx.new_cdp_session(pg)
    def tp(t,y):cdp.send('Input.dispatchTouchEvent',{'type':t,'touchPoints':[] if t=='touchEnd' else [{'x':200,'y':y}]})
    def pull(dist,steps=12):
        tp('touchStart',200)
        for i in range(1,steps+1):tp('touchMove',200+dist*i/steps);pg.wait_for_timeout(16)
    pg.evaluate("window.scrollTo(0,0)");pg.wait_for_timeout(300)
    pull(100);ck('short pull shows indicator, not ready',pg.evaluate("getComputedStyle(document.getElementById('ptr')).opacity")=='1' and not pg.evaluate("document.getElementById('ptr').classList.contains('ready')"))
    tp('touchEnd',0);pg.wait_for_timeout(500)
    ck('short pull cancels',not pg.evaluate("document.getElementById('ptr').classList.contains('spin')"))
    pull(220);pg.wait_for_timeout(50);pg.screenshot(path='../ptr1.png')
    ck('long pull ready',pg.evaluate("document.getElementById('ptr').classList.contains('ready')"))
    tp('touchEnd',0);pg.wait_for_timeout(150)
    ck('spinner runs',pg.evaluate("document.getElementById('ptr').classList.contains('spin')"))
    pg.screenshot(path='../ptr2.png')
    pg.wait_for_timeout(1300)
    pg.wait_for_timeout(2500);sp=pg.evaluate("document.getElementById('ptr').classList.contains('spin')");tt=pg.inner_text('#toast');ck('finishes and shows toast',not sp and ('Up to date' in tt or 'synced' in tt),(sp,tt))
    ck('content back in place',pg.evaluate("document.getElementById('ov').style.translate") in ('',None))
    # not when scrolled down
    pg.evaluate("window.scrollTo(0,400)");pg.wait_for_timeout(300)
    pull(220);tp('touchEnd',0);pg.wait_for_timeout(200)
    ck('no refresh when scrolled down',not pg.evaluate("document.getElementById('ptr').classList.contains('spin')"))
    # works on Finances tab
    pg.evaluate("window.scrollTo(0,0)");pg.tap('.tabbar [data-tab=money]');pg.wait_for_timeout(700)
    pull(220);tp('touchEnd',0);pg.wait_for_timeout(150)
    ck('works on Finances tab',pg.evaluate("document.getElementById('ptr').classList.contains('spin')"))
    pg.wait_for_timeout(1300)
    # not while a sheet is open
    pg.tap('[data-settings]');pg.wait_for_timeout(700)
    pull(220);tp('touchEnd',0);pg.wait_for_timeout(150)
    ck('ignored while a sheet is open',not pg.evaluate("document.getElementById('ptr').classList.contains('spin')"))
    ck('no errors',not errs,errs)
    b.close()
print(sum(R),'/',len(R))
