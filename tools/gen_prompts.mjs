// Reads the app's built-in AI instructions out of public/index.html and writes api/_prompts.js,
// so the server only accepts the app's own prompts. Run after every app build: node tools/gen_prompts.mjs
import fs from 'node:fs';
import vm from 'node:vm';
import crypto from 'node:crypto';

const root = new URL('..', import.meta.url).pathname;
const html = fs.readFileSync(root + 'public/index.html', 'utf8');
const lit = name => {
  const i = html.indexOf('const ' + name + '=`'); if (i < 0) throw new Error('missing ' + name);
  const j = html.indexOf('`;', i + name.length + 8);
  return vm.runInNewContext(html.slice(i + name.length + 7, j + 1));
};
const CMD = lit('CMD_PROMPT'), RULES = lit('ASK_RULES'), AI = lit('AI_PROMPT'), IM = lit('IM_PROMPT'), SCAN = lit('SCAN_PROMPT'), CREDIT = lit('CREDIT_PROMPT');
const k = "const res=await sampleFn.json(CMD_PROMPT+'\\n\\n'+ASK_RULES+";
const a = html.indexOf(k); if (a < 0) throw new Error('missing Ask call');
const b = html.indexOf('+askContext()', a);
let tail = vm.runInNewContext(html.slice(a + k.length, b));
const MARK = '\n\nTheir current data:\n';
if (!tail.endsWith(MARK)) throw new Error('Ask prompt layout changed');
tail = tail.slice(0, -MARK.length);
const askSystem = CMD + '\n\n' + RULES + tail;
const sha = s => crypto.createHash('sha256').update(s, 'utf8').digest('hex');
const P = {
  ask: { start: CMD.slice(0, 60), marker: '\n\nTheir current data:\n', hash: sha(askSystem) },
  setup: { start: AI.slice(0, 60), marker: '\n\nTheir description:\n' },
  import: { start: IM.slice(0, 60), marker: '\n\nSTATEMENT TEXT:\n' },
  scan: { start: SCAN.slice(0, 60), marker: '\n\ntodayRealDate: ' },
  credit: { start: CREDIT.slice(0, 60), marker: '\n\ntodayRealDate: ' },
  translate: { start: 'Translate these user-interface strings from a friendly personal budgeting app called Sprout into ', marker: '' }
};
fs.writeFileSync(root + 'api/_prompts.js', '// Generated by tools/gen_prompts.mjs from public/index.html. Do not edit by hand.\nexport const PROMPTS = ' + JSON.stringify(P, null, 2) + ';\n');
console.log('wrote api/_prompts.js; Ask instructions are', askSystem.length, 'characters (about', Math.round(askSystem.length / 4), 'tokens, cached)');
